def select_robot_ml(order):

    available = [

        r for r in robots

        if (
            not r.failed
            and r.task is None
            and r.status == "IDLE"
            and r.battery > CRITICAL_BATTERY
        )
    ]

    if not available:

        return None

    rows = []

    for r in available:

        d = dist(
            (r.x, r.y),
            PICKUP
        )

        shelf = shelf_point(
            r,
            order.shelf
        )

        task_distance = (

            dist(
                PICKUP,
                shelf
            )

            +

            dist(
                shelf,
                DELIVERY
            )
        )

        eta = d / max(
            r.speed,
            0.1
        )

        priority = {

            "LOW": 1,
            "MEDIUM": 2,
            "HIGH": 3

        }[order.priority]

        rows.append({

            "Robot": r.name,

            "battery": r.battery,

            "distance_to_task": d,

            "speed": r.speed,

            "workload": r.workload,

            "payload_ratio": 0.55,

            "congestion": congestion(r),

            "task_distance": task_distance,

            "priority": priority,

            "eta_seconds": eta
        })

    table = pd.DataFrame(
        rows
    )

    X = table[
        FEATURES
    ]

    proba = MODEL.predict_proba(
        X
    )

    classes = list(
        MODEL.classes_
    )

    scores = []

    for i, robot_name in enumerate(
        table["Robot"]
    ):

        if robot_name in classes:

            j = classes.index(
                robot_name
            )

            score = proba[i][j]

        else:

            score = 0

        scores.append(
            score
        )

    table[
        "ML_Probability"
    ] = np.array(
        scores
    ) * 100

    # Safety
    for i, r in enumerate(
        available
    ):

        if r.battery <= LOW_BATTERY:

            table.loc[
                i,
                "ML_Probability"
            ] = 0

    best = table[
        "ML_Probability"
    ].idxmax()

    selected_name = table.loc[
        best,
        "Robot"
    ]

    selected = next(
        r for r in available
        if r.name == selected_name
    )

    selected.reason = (

        f"ML {table.loc[best, 'ML_Probability']:.1f}% | "
        f"Battery {selected.battery:.0f}% | "
        f"Distance {table.loc[best, 'distance_to_task']:.0f} | "
        f"Workload {selected.workload}"
    )

    metrics[
        "ml_decisions"
    ] += 1

    return selected


