def to_grid(x, y):

    return (
        int(round(x / GRID)),
        int(round(y / GRID))
    )


def to_world(g):

    return (
        g[0] * GRID,
        g[1] * GRID
    )


def valid_grid(g):

    x, y = to_world(g)

    return not is_blocked(
        x,
        y
    )


