# ============================================================
# 14. COLLISION CHECK
# ============================================================

def is_blocked(x, y):

    if x < 3 or x > W - 3:
        return True

    if y < 3 or y > H - 3:
        return True

    for rect in shelf_rects():

        if inside_rect(
            x,
            y,
            rect,
            ROBOT_RADIUS
        ):

            return True

    for rect in OBSTACLES:

        if inside_rect(
            x,
            y,
            rect,
            ROBOT_RADIUS
        ):

            return True

    return False


