# ============================================================
# 17. ROBOT LABEL MATCHING
# ============================================================
#
# THIS IS THE MAIN FIX.
#
# The model may contain:
#
# R1 R2 R3 R4 R5
#
# OR
#
# 1 2 3 4 5
#
# OR
#
# 0 1 2 3 4
#
# OR
#
# Robot_1 Robot_2 ...
#
# This function converts the model class into
# the corresponding WAREX robot ID.
#
# ============================================================

def normalize_robot_label(label):

    text = str(label).strip().upper()

    # Direct match
    if text in [
        "R1",
        "R2",
        "R3",
        "R4",
        "R5"
    ]:

        return text


    # Extract number
    numbers = re.findall(
        r"\d+",
        text
    )


    if len(numbers) > 0:

        number = int(
            numbers[0]
        )


        # Robot 1-5
        if number >= 1 and number <= 5:

            return "R" + str(number)


    return None


