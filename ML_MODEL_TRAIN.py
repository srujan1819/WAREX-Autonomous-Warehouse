    visited = set()

    while queue:

        _, current = heapq.heappop(
            queue
        )

        if current in visited:

            continue

        visited.add(
            current
        )

        if current == goal:

            path = []

            while current in came:

                path.append(
                    to_world(current)
                )

                current = came[current]

            path.append(
                to_world(start)
            )

            path.reverse()

            return path

        for dx, dy in directions:

            nxt = (
                current[0] + dx,
                current[1] + dy
            )

            if not valid_grid(nxt):

                continue

            new_cost = (
                cost[current]
                +
                math.sqrt(
                    dx * dx + dy * dy
                )
            )

            if (
                nxt not in cost
                or
                new_cost < cost[nxt]
            ):

                cost[nxt] = new_cost

                heuristic = math.hypot(
                    nxt[0] - goal[0],
                    nxt[1] - goal[1]
                )

                heapq.heappush(
                    queue,
                    (
                        new_cost + heuristic,
                        nxt
                    )
                )

                came[nxt] = current

    return []


