def calculate_risk(row):
    if row["Battery"] <= 30:
        return "HIGH"
    elif row["Battery"] <= 50:
        return "MEDIUM"
    elif row["Workload"] >= 4:
        return "MEDIUM"
    elif row["Obstacles"] >= 3:
        return "HIGH"
    else:
        return "LOW"


def calculate_score(row, priority):
    score = 0

    # Order priority
    score += priority_score[priority] * 100

    # Battery
    score += row["Battery"] * 2

    # Distance
    score -= row["Distance"] * 0.5

    # Workload
    score -= row["Workload"] * 10

    # Obstacles
    score -= row["Obstacles"] * 20

    # Very low battery penalty
    if row["Battery"] <= 30:
        score -= 100

    return score


