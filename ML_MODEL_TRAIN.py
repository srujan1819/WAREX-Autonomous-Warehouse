def charge_robot(
    robot
):

    if robot.status != "GO CHARGE":

        return

    if dist(
        (robot.x, robot.y),
        CHARGE
    ) > 3:

        move_robot(
            robot
        )

        return

    robot.status = "CHARGING"

    robot.battery += CHARGE_RATE

    if robot.battery >= 95:

        robot.battery = 95

        robot.status = "IDLE"

        log(
            f"{robot.name}: CHARGED → AVAILABLE"
        )


