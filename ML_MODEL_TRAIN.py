def run_judge_decision():

    rows = []

    for robot_name, values in robots_demo.items():

        row = values.copy()

        row["Robot"] = robot_name

        row["task_distance"] = (
            state["task_distance"]
        )

        row["priority"] = (
            state["priority"]
        )

        row["eta_seconds"] = (
            row["distance_to_task"]
            /
            max(
                row["speed"],
                0.01
            )
        )

        rows.append(
            row
        )

    table = pd.DataFrame(
        rows
    )

    # --------------------------------------------------------
    # RULE-BASED BEFORE ML
    # --------------------------------------------------------

    table["Rule_Score"] = (

        table["priority"] * 100

        +

        table["battery"] * 2

        -

        table["distance_to_task"] * 0.5

        -

        table["workload"] * 10

        -

        table["congestion"] * 20
    )

    table.loc[
        table["battery"] <= 30,
        "Rule_Score"
    ] -= 100

    # Failed robots cannot be selected
    for robot in state["failed"]:

        table.loc[
            table["Robot"] == robot,
            "Rule_Score"
        ] = -999999


    # --------------------------------------------------------
    # ML
    # --------------------------------------------------------

    X = table[
        JUDGE_FEATURES
    ]

    probabilities = (
        judge_model.predict_proba(
            X
        )
    )

    classes = list(
        judge_model.classes_
    )

    ml_probability = []

    for i, robot_name in enumerate(
        table["Robot"]
    ):

        if robot_name in classes:

            class_index = classes.index(
                robot_name
            )

            probability = (
                probabilities[i][
                    class_index
                ]
                * 100
            )

        else:

            probability = 0

        # Safety layer
        if robot_name in state["failed"]:

            probability = 0

        if (
            table.loc[
                i,
                "battery"
            ]
            <= 10
        ):

            probability = 0

        ml_probability.append(
            probability
        )

    table[
        "ML_Probability"
    ] = ml_probability


    # --------------------------------------------------------
    # SELECTIONS
    # --------------------------------------------------------

    rule_index = table[
        "Rule_Score"
    ].idxmax()

    ml_index = table[
        "ML_Probability"
    ].idxmax()

    rule_robot = table.loc[
        rule_index,
        "Robot"
    ]

    ml_robot = table.loc[
        ml_index,
        "Robot"
    ]

    ml_confidence = table.loc[
        ml_index,
        "ML_Probability"
    ]


    # --------------------------------------------------------
    # WHY
    # --------------------------------------------------------

    selected = table.loc[
        ml_index
    ]

    reasons = []

    reasons.append(
        f"Battery {selected['battery']:.0f}%"
    )

    reasons.append(
        f"Distance {selected['distance_to_task']:.0f}"
    )

    reasons.append(
        f"Speed {selected['speed']:.2f}"
    )

    reasons.append(
        f"Workload {selected['workload']}"
    )

    reasons.append(
        f"Congestion {selected['congestion']}"
    )

    reasons.append(
        f"ETA {selected['eta_seconds']:.1f}s"
    )


    return (
        table,
        rule_robot,
        ml_robot,
        ml_confidence,
        reasons
    )


