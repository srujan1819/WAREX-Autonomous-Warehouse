def reached(
    robot
):

    # Rescue
    if robot.status == "RESCUE":

        complete_rescue(
            robot
        )

        return

    # Charging
    if robot.status == "GO CHARGE":

        robot.status = "CHARGING"

        return

    task = robot.task

    if task is None:
        return

    # Pickup
    if task.stage == "TO_PICKUP":

        task.stage = "TO_SHELF"

        robot.status = "TO SHELF"

        set_target(
            robot,
            shelf_point(
                robot,
                task.shelf
            )
        )

        log(
            f"{robot.name} reached PICKUP → order received"
        )

    # Shelf
    elif task.stage == "TO_SHELF":

        task.stage = "TO_DELIVERY"

        task.box_visible = True

        robot.box = True

        robot.status = "TO DELIVERY"

        set_target(
            robot,
            DELIVERY
        )

        log(
            f"{robot.name} reached SHELF → product loaded"
        )

    # Delivery
    elif task.stage == "TO_DELIVERY":

        task.stage = "COMPLETED"

        robot.task = None

        robot.workload = 0

        robot.status = "IDLE"

        robot.box = False

        metrics[
            "completed"
        ] += 1

        log(
            f"{robot.name} delivered {task.id} ✓"
        )


