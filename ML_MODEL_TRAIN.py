def initiate_handover(
    source
):

    if source.task is None:
        return

    if source.waiting_rescue:
        return

    candidates = [

        r for r in robots

        if (
            r.name != source.name
            and
            r.task is None
            and
            not r.failed
            and
            r.status == "IDLE"
            and
            r.battery > LOW_BATTERY
        )
    ]

    if not candidates:

        source.waiting_rescue = True

        source.status = "HANDOFF WAIT"

        log(
            f"{source.name} waiting for rescue robot"
        )

        return

    rescue = min(
        candidates,
        key=lambda r:
        dist(
            (r.x, r.y),
            (source.x, source.y)
        )
    )

    source.waiting_rescue = True

    source.status = "HANDOFF WAIT"

    rescue.status = "RESCUE"

    rescue.rescue_target = source.name

    set_target(
        rescue,
        (source.x, source.y)
    )

    metrics[
        "handovers"
    ] += 1

    source.task.handover += 1

    log(
        f"HANDOVER → {rescue.name} rescuing {source.name}"
    )


