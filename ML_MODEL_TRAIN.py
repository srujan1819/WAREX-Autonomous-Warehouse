# 26. MOVE ROBOT
# ============================================================

def move_robot(
    robot
):

    if robot.failed:
        return

    if robot.status in [
        "IDLE",
        "HANDOFF WAIT",
        "CHARGING"
    ]:
        return

    if not robot.path:
        return

    target = robot.path[0]

    dx = target[0] - robot.x

    dy = target[1] - robot.y

    d = math.hypot(
        dx,
        dy
    )

    if d < 0.7:

        robot.x = target[0]

        robot.y = target[1]

        robot.path.pop(0)

        if not robot.path:

            reached(
                robot
            )

        return

    step = min(
        robot.speed * MOVE_STEP,
        d
    )

    nx = robot.x + (
        dx / d
    ) * step

    ny = robot.y + (
        dy / d
    ) * step

    # Never enter shelves or obstacles
    if is_blocked(
        nx,
        ny
    ):

        robot.replans += 1

        metrics[
            "replans"
        ] += 1

        log(
            f"{robot.name}: BLOCKED → A* REPLAN"
        )

        robot.path = astar(
            (robot.x, robot.y),
            robot.target
        )

        return

    travelled = dist(
        (robot.x, robot.y),
        (nx, ny)
    )

    robot.x = nx

    robot.y = ny

    metrics[
        "distance"
    ] += travelled

    battery_before = robot.battery

    robot.battery -= (
        travelled * BATTERY_DRAIN
    )

    battery_used = max(
        0,
        battery_before - robot.battery
    )

    metrics[
        "battery"
    ] += battery_used

    # Low battery
    if (
        robot.task is not None
        and
        robot.battery <= LOW_BATTERY
    ):

        initiate_handover(
            robot
        )


