# 17. SHELF APPROACH POINT
# ============================================================

def shelf_point(robot, shelf):

    x, y, w, h = shelf

    candidates = [

        (x - 4, y + h / 2),

        (x + w + 4, y + h / 2),

        (x + w / 2, y - 4),

        (x + w / 2, y + h + 4)
    ]

    candidates = [

        p for p in candidates

        if not is_blocked(
            p[0],
            p[1]
        )
    ]

    if not candidates:

        return (
            x - 4,
            y + h / 2
        )

    return min(
        candidates,
        key=lambda p:
        dist(
            (robot.x, robot.y),
            p
        )
    )


