def inside_rect(
    x,
    y,
    rect,
    padding=0
):

    x1, y1, x2, y2 = rect

    return (
        x1 - padding <= x <= x2 + padding
        and
        y1 - padding <= y <= y2 + padding
    )


# ============================================================
